import { productById } from './catalog'

const minute = 60 * 1000

function item(productId, qty, extra = {}) {
  const product = productById(productId)
  return {
    id: `${productId}-${qty}-${extra.note || 'plain'}`,
    productId,
    name: product.name,
    qty,
    station: product.station,
    unitPrice: product.price + (extra.extra || 0),
    variation: extra.variation || null,
    choices: extra.choices || [],
    addons: extra.addons || [],
    instructions: extra.note || '',
    ready: Boolean(extra.ready),
  }
}

